#!/usr/bin/env python3
"""Generates src/HrtfData.hpp from the MIT KEMAR HRTF tables in mit-hrtf-lib.

Only the horizontal plane (elevation 0°) is kept, since our speakers are all at ear height.
The diffuse-field equalised set is used, which suits headphone listening.

Usage:
    git clone https://github.com/zodsoft/mit-hrtf-lib
    python3 tools/make_hrtf.py mit-hrtf-lib

Data: MIT Media Lab KEMAR measurements, Bill Gardner and Keith Martin (1994),
provided without usage restrictions. Tables converted by Aristotel Digenis (mit-hrtf-lib, MIT License).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATES = [44100, 48000, 88200, 96000]
TAPS = {44100: 128, 48000: 140, 88200: 256, 96000: 279}
NUM_AZIMUTHS = 37  # 0° to 180° in 5° steps

ENTRY = re.compile(r"//\s*H(-?\d+)e(\d+)a\.wav\s*\n\s*\{([^{}]*)\},\s*\{([^{}]*)\}")


def load(lib, rate):
	path = os.path.join(lib, "source", "diffuse", f"mit_hrtf_diffuse_{rate}.h")
	src = open(path, encoding="latin-1").read()
	left = {}
	right = {}
	for m in ENTRY.finditer(src):
		elev, azim = int(m.group(1)), int(m.group(2))
		if elev != 0:
			continue
		l = [int(v) for v in m.group(3).replace("\n", "").split(",") if v.strip()]
		r = [int(v) for v in m.group(4).replace("\n", "").split(",") if v.strip()]
		assert len(l) == TAPS[rate] and len(r) == TAPS[rate], (rate, azim, len(l), len(r))
		left[azim] = l
		right[azim] = r
	azimuths = sorted(left)
	assert azimuths == list(range(0, 181, 5)), azimuths
	return [left[a] for a in azimuths], [right[a] for a in azimuths]


def fmt(rows):
	return ",\n".join("\t{" + ",".join(str(v) for v in row) + "}" for row in rows)


def main():
	if len(sys.argv) != 2:
		print(__doc__)
		sys.exit(1)
	lib = sys.argv[1]
	out = [
		"#pragma once",
		"// Generated by tools/make_hrtf.py. Do not edit by hand.",
		"//",
		"// Head-related impulse responses for the horizontal plane (elevation 0°), azimuth 0° to 180°",
		"// in 5° steps, for a source on the listener's right. Mirror (swap the ears) for the left side.",
		"// Diffuse-field equalised. 16-bit integers, scale by 1/32768.",
		"//",
		"// Data: MIT Media Lab KEMAR measurements by Bill Gardner and Keith Martin (1994),",
		"// provided without usage restrictions. Tables converted by Aristotel Digenis",
		"// (mit-hrtf-lib, MIT License, see LICENSE-mit-hrtf-lib.txt).",
		"",
		"namespace hrtf {",
		"",
		f"static const int NUM_AZIMUTHS = {NUM_AZIMUTHS};",
		"static const int AZIMUTH_STEP = 5;",
		"",
	]
	sets = []
	for rate in RATES:
		left, right = load(lib, rate)
		taps = TAPS[rate]
		out.append(f"static const short LEFT_{rate}[NUM_AZIMUTHS][{taps}] = {{\n{fmt(left)}\n}};")
		out.append(f"static const short RIGHT_{rate}[NUM_AZIMUTHS][{taps}] = {{\n{fmt(right)}\n}};")
		out.append("")
		sets.append(f"\t{{{rate}, {taps}, &LEFT_{rate}[0][0], &RIGHT_{rate}[0][0]}},")
	out += [
		"struct Set {",
		"\tint sampleRate;",
		"\tint taps;",
		"\t/** NUM_AZIMUTHS rows of `taps` samples each. */",
		"\tconst short* left;",
		"\tconst short* right;",
		"};",
		"",
		f"static const int NUM_SETS = {len(RATES)};",
		"static const Set SETS[NUM_SETS] = {",
		*sets,
		"};",
		"",
		"} // namespace hrtf",
		"",
	]
	dest = os.path.join(ROOT, "src", "HrtfData.hpp")
	with open(dest, "w") as f:
		f.write("\n".join(out))
	print("wrote src/HrtfData.hpp")


if __name__ == "__main__":
	main()
